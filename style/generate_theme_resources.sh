#!/bin/bash
# Generate all theme resources from themes_list.txt
# Usage: generate_theme_resources.sh <themes_list.txt> <style_dir> <themes_dir>

set -e

THEMES_LIST="$1"
STYLE_DIR="$2"
THEMES_DIR="$3"

if [[ ! -f "$THEMES_LIST" ]]; then
    echo "Error: $THEMES_LIST not found"
    exit 1
fi

# Read themes (first = default)
BUILTIN_THEMES=()
while IFS= read -r line || [[ -n "$line" ]]; do
    [[ -z "$line" || "$line" =~ ^# ]] && continue
    BUILTIN_THEMES+=("$line")
done < "$THEMES_LIST"

if [[ ${#BUILTIN_THEMES[@]} -eq 0 ]]; then
    echo "Error: No themes found in $THEMES_LIST"
    exit 1
fi

DEFAULT_THEME="${BUILTIN_THEMES[0]}"

# Get all theme directories from themes dir
ALL_THEMES=()
for theme_dir in "$THEMES_DIR"/*/; do
    theme=$(basename "$theme_dir")
    [[ -d "$theme_dir" ]] || continue
    [[ "$theme" == *.sh ]] && continue
    [[ "$theme" == *.pro ]] && continue
    [[ "$theme" == *.pri ]] && continue
    [[ -f "$theme_dir/$theme.svg" && -f "$theme_dir/$theme.cfg" ]] || continue
    ALL_THEMES+=("$theme")
done

# Find non-built-in themes
NON_BUILTIN_THEMES=()
for theme in "${ALL_THEMES[@]}"; do
    is_builtin=false
    for bt in "${BUILTIN_THEMES[@]}"; do
        if [[ "$theme" == "$bt" ]]; then
            is_builtin=true
            break
        fi
    done
    if [[ "$is_builtin" == false ]]; then
        NON_BUILTIN_THEMES+=("$theme")
    fi
done

echo "Generating theme resources..."
echo "Default theme: $DEFAULT_THEME"
echo "Built-in themes: ${BUILTIN_THEMES[*]}"
echo "Non-built-in themes: ${NON_BUILTIN_THEMES[*]}"

# ============================================================
# 1. Generate builtinthemes.qrc
# ============================================================
cat > "$STYLE_DIR/builtinthemes.qrc" <<'EOT'
<RCC>
  <qresource prefix="/qsvgstyle" >
EOT

for theme in "${BUILTIN_THEMES[@]}"; do
    echo "    <file>themes/$theme/$theme.svg</file>" >> "$STYLE_DIR/builtinthemes.qrc"
    echo "    <file>themes/$theme/$theme.cfg</file>" >> "$STYLE_DIR/builtinthemes.qrc"
done

cat >> "$STYLE_DIR/builtinthemes.qrc" <<'EOT'
  </qresource>
</RCC>
EOT

# ============================================================
# 2. Generate builtin_themes.h
# ============================================================
cat > "$STYLE_DIR/builtin_themes.h" <<'EOT'
// Generated by generate_theme_resources.sh - DO NOT EDIT
#ifndef BUILTIN_THEMES_H
#define BUILTIN_THEMES_H

static const char* QSVGSTYLE_BUILTIN_THEMES_LIST[] = {
EOT

for theme in "${BUILTIN_THEMES[@]}"; do
    echo "    \"$theme\"," >> "$STYLE_DIR/builtin_themes.h"
done

cat >> "$STYLE_DIR/builtin_themes.h" <<EOT
    nullptr
};

static const char* QSVGSTYLE_BUILTIN_DEFAULT_THEME = "$DEFAULT_THEME";

#endif // BUILTIN_THEMES_H
EOT

# ============================================================
# 3. Generate themes_install.pri
# ============================================================
INSTALL_PRI_FILE="$THEMES_DIR/themes_install.pri"
cat > "$INSTALL_PRI_FILE" <<'EOT'
# Generated by generate_theme_resources.sh - DO NOT EDIT
# Install non-built-in themes

unix:isEmpty(PREFIX) {
  PREFIX = /usr
}

windows:isEmpty(PREFIX) {
  PREFIX = $$(MSYSTEM_PREFIX)
}

EOT

if [[ ${#NON_BUILTIN_THEMES[@]} -gt 0 ]]; then
    cat >> "$INSTALL_PRI_FILE" <<EOT
nonbuiltin_themes.path = \$\$PREFIX/share/QSvgStyle
nonbuiltin_themes.files = \\
EOT

    for theme in "${NON_BUILTIN_THEMES[@]}"; do
        echo "    style/themes/$theme/$theme.svg \\" >> "$INSTALL_PRI_FILE"
        echo "    style/themes/$theme/$theme.cfg \\" >> "$INSTALL_PRI_FILE"
    done

    cat >> "$INSTALL_PRI_FILE" <<EOT

INSTALLS += nonbuiltin_themes
EOT
else
    echo "# No non-built-in themes to install" >> "$INSTALL_PRI_FILE"
fi

echo "Generated all theme resources in $STYLE_DIR and $THEMES_DIR"
